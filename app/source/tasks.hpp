#pragma once

#include <functional>

/// Фоновые задачи приложения.
///
/// Почему не brls::async: у borealis это один поток, который забирает всю
/// очередь, выполняет её последовательно и спит по 500 мс между партиями
/// (library/lib/core/thread.cpp). На таком механизме обложки появлялись
/// волнами с задержкой до полусекунды, а скачивание трейлера занимало
/// единственный рабочий поток на десятки секунд — всё это время не грузилось
/// вообще ничего.
///
/// Поэтому здесь два раздельных канала:
///   io()    — небольшой пул под короткие задачи (обложки, скриншоты);
///   heavy() — отдельный поток под долгие (скачивание ролика, инициализация
///             сети), чтобы они не занимали пул.
///
/// Возврат в UI-поток по-прежнему через brls::sync — borealis не потокобезопасен.
namespace tasks
{

void start();
void stop();

/// Приложение закрывается и длинные операции пора бросать.
///
/// Нужна загрузкам: curl без этого досиживает свои таймауты, и выход из
/// программы занимал до минуты — три попытки по двадцать секунд на каждую
/// картинку, которую io-поток начал качать перед самым закрытием.
bool shuttingDown();

/// Поднимает флаг остановки, никого не дожидаясь. Позволяет разбудить ожидающих
/// до того, как stop() начнёт джойнить потоки.
void requestStop();

void io(std::function<void()> task);
void heavy(std::function<void()> task);

}  // namespace tasks
