#pragma once

#include <string>

/// Замеры времени и счётчики для поиска узких мест.
///
/// По строкам журнала вида «каталог показан» нельзя понять, что именно заняло
/// секунду — чтение с romfs, разбор JPEG или пересчёт раскладки. Здесь два инструмента. Scope меряет отдельную операцию и пишет её длительность
/// сразу. Счётчики копятся всё время работы и выводятся при выходе — по ним
/// видно то, что в отдельной строке не разглядеть: сколько обложек пришло из
/// кэша, а сколько читалось с карты заново.
namespace perf
{

/// Замер одной операции. Пишет в журнал длительность при разрушении.
///
/// Порог нужен, чтобы не засорять журнал: интересны только те случаи, когда
/// операция заметна глазу. Всё быстрее порога просто не печатается.
///
/// Пустое имя означает «мерить, но не писать»: результат забирают через
/// elapsedMs() и складывают в счётчик.
class Scope
{
  public:
    explicit Scope(std::string what, double thresholdMs = 0.0);
    ~Scope();

    /// Длительность на текущий момент, миллисекунды.
    double elapsedMs() const;

  private:
    std::string what;
    double threshold;
    long long startedUs;
};

/// Счётчики за всё время работы.
enum class Counter
{
    CoverFromCache,   ///< обложка нашлась в кэше текстур
    CoverFromDisk,    ///< обложку пришлось читать с romfs и разбирать
    CoverDropped,     ///< загрузка отменена: строка уехала с экрана
    CoverDecodeMs,    ///< суммарное время разбора JPEG
    CatalogQueries,   ///< выборок из каталога
    CatalogMs,        ///< суммарное время выборок
    NetFetches,       ///< загрузок из сети
    NetMs,            ///< суммарное время загрузок
    Frames,           ///< отрисовано кадров
    FramesSlow,       ///< кадров дольше SLOW_FRAME_MS — видимые рывки
};

/// Кадр длиннее считается рывком. 60 Гц — это 16.7 мс на кадр; два пропущенных
/// подряд уже заметны глазом на прокрутке.
constexpr double SLOW_FRAME_MS = 33.0;

void count(Counter counter, long long value = 1);

/// Выводит накопленное в журнал. Зовётся при завершении.
void report();

}  // namespace perf
