#pragma once

#include <borealis.hpp>

#include <string>

/// Кэш готовых текстур обложек.
///
/// Плитки сетки переиспользуются, и при каждом переиспользовании обложка
/// читалась с romfs и заново разбиралась из JPEG. Прокрутка вниз и обратно
/// означала повторное чтение и повторный разбор одних и тех же файлов —
/// сотни раз за минуту листания. Разбор мы уже унесли из UI-потока, но работа
/// от этого никуда не делась, просто перестала ронять кадры.
///
/// Здесь готовая текстура живёт до вытеснения, и повторный показ той же игры
/// не стоит ничего: ни чтения, ни разбора, ни загрузки в видеопамять.
///
/// Все методы — только из UI-потока: они трогают контекст nanovg.
namespace covers
{

/// Текстура обложки или 0, если её ещё нет в кэше.
int find(const std::string& file);

/// Кладёт готовую текстуру и возвращает ту, что теперь в кэше за этим файлом.
///
/// Возвращаемое значение обязательно к использованию: если обложку успели
/// загрузить дважды — а это обычное дело, предзагрузка следующей строки идёт
/// одновременно с загрузкой самой плитки, — кэш оставляет первую текстуру, а
/// вторую освобождает. Показывать надо ту, что вернули, иначе на экране
/// окажется уже удалённая, то есть пустое место.
///
/// Владение переходит кэшу: вид, которому текстуру отдали, не должен её
/// освобождать (Image::setFreeTexture(false)).
int put(const std::string& file, int texture);

/// Сколько текстур держим. Плитка 160×160 логических точек в доке рисуется как
/// 240 физических, обложка ровно такая же — 240×240 в RGBA, то есть 225 КБ на
/// штуку. Сотня даёт 22 МБ: заметно больше, чем помещается на экране (около
/// 20), и заметно меньше, чем есть памяти даже в режиме апплета.
constexpr int LIMIT = 100;

/// Папка с обложками и снимками: в romfs на приставке, рядом с бинарником на ПК.
/// Одно место для всех, кто читает картинки из ресурсов.
#ifdef __SWITCH__
inline constexpr const char* ART_DIR = "romfs:/art/";
#else
inline constexpr const char* ART_DIR = "resources/art/";
#endif

/// Помечает обложку как показываемую прямо сейчас — её нельзя вытеснять.
///
/// Без этого кэш освобождал текстуру, на которую ещё ссылается видимая плитка:
/// сотни хватает на четырнадцать строк прокрутки, а обложки, загруженные на
/// другом экране, вытеснялись первыми. Плитка при этом не перезагружала
/// картинку — для неё игра не менялась, — и на месте обложки оставался серый
/// прямоугольник. Ровно это видно в разделе «Скрытые» после листания каталога.
///
/// Считается по числу владельцев: одну обложку могут показывать сразу
/// несколько плиток на разных экранах.
void pin(const std::string& file);
void unpin(const std::string& file);

/// Читает обложку в кэш заранее, если её там ещё нет. Ничего не рисует.
///
/// Нужна для строки, которая вот-вот появится: к моменту прокрутки обложка уже
/// готова, и вместо пустого места сразу видна картинка. Ставится в конец
/// очереди — видимые строки важнее.
void warm(const std::string& file);

/// Освобождает все текстуры. Нужен при выходе: иначе nanovg получит удаление
/// уже разрушенного контекста.
void clear();

}  // namespace covers
