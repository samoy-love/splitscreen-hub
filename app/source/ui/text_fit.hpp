#pragma once

#include <string>

/// Подгонка текста под доступную ширину.
///
/// Названия папок задаёт пользователь, до 32 символов. В списке библиотеки на
/// имя приходится около 120 точек — это меньше десяти широких букв, так что уже
/// «Вечер с друзьями» не помещается. Label в borealis по умолчанию переносит
/// строку, и вместо ровного списка получаются кнопки разной высоты.
///
/// Мерим настоящим шрифтом через nanovg, а не считаем символы: у кириллицы,
/// латиницы и цифр разная ширина, и «двадцать символов» ничего не гарантирует.
namespace textfit
{

/// Обрезает текст до maxWidth, добавляя многоточие. Если помещается целиком —
/// возвращает как есть. Только из UI-потока: обращается к контексту nanovg.
std::string ellipsize(const std::string& text, float maxWidth, float fontSize);

}  // namespace textfit
