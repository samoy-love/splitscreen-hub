#pragma once

#include <borealis.hpp>

#include <chrono>

/// Подпись, залитая переливающимся градиентом.
///
/// Нужна ровно одному месту — названию приложения в строке вкладок. Оно стоит
/// на экране всегда, и это единственная надпись, которую можно оживить, не
/// мешая читать: остальное на главной — это названия игр, счётчики и подсказки,
/// то есть текст, который читают, а не разглядывают.
///
/// Обычный brls::Label так не покрасить: он сам зовёт nvgFillColor перед
/// выводом, и любая заливка, выставленная снаружи, до текста не доходит.
/// Поэтому свой вывод — nvgFillPaint с линейным градиентом, а сама раскладка,
/// шрифт и кегль остаются от Label.
///
/// Перелив сделан двумя движениями. Градиент из двух цветов ходит вдоль надписи
/// туда-сюда по синусу — так цвета текут сквозь буквы и петля сходится сама
/// собой, без скачка на стыке. Поверх раз в несколько секунд проходит светлый
/// блик — он и читается как «перелив», а не как «залито двумя цветами».
class GradientLabel : public brls::Label
{
  public:
    GradientLabel();

    static brls::View* create();

    void draw(NVGcontext* vg, float x, float y, float width, float height, brls::Style style,
              brls::FrameContext* ctx) override;

  private:
    /// Сколько длится полный проход цветов туда и обратно.
    static constexpr float FLOW_PERIOD_MS = 5200.0f;

    /// Период блика вместе с паузой между проходами. Сам проход занимает
    /// FLASH_PART от него: блик, идущий без остановки, превращает надпись в
    /// вывеску.
    static constexpr float FLASH_PERIOD_MS = 6400.0f;
    static constexpr float FLASH_PART      = 0.22f;

    /// Ширина блика в долях ширины надписи.
    static constexpr float FLASH_WIDTH = 0.30f;

    std::chrono::steady_clock::time_point started;

    /// Миллисекунды от создания. Точка отсчёта своя, а не общие часы: иначе
    /// надпись появлялась бы на случайной фазе перелива.
    float elapsedMs() const;
};
