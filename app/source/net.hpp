#pragma once

#include <string>
#include <vector>

/// Загрузка картинок из сети с кэшем на SD-карте.
///
/// Обложки лежат в romfs и доступны офлайн, а скриншотов 20 тысяч — в релиз их
/// не положишь. Поэтому они тянутся при открытии карточки и остаются в
/// sdmc:/switch/splitscreen-hub/cache/, чтобы второй раз не качать.
namespace net
{

/// Инициализирует сеть. Без неё загрузка просто не работает, приложение живёт.
void init();
void shutdown();

/// Ждёт готовности сети до указанного времени. Инициализация идёт в фоне,
/// и карточка, открытая в первую секунду после запуска, иначе молча осталась
/// бы без скриншотов — без единой повторной попытки.
bool waitReady(int milliseconds);

/// Будит всех, кто ждёт в waitReady. Зовётся при остановке, чтобы ожидание сети
/// не задерживало выход из приложения.
void wakeWaiters();

/// true, если init() отработал успешно. Видео и скриншоты используют это,
/// чтобы не пытаться качать вникуда и сразу показать понятное сообщение.
bool isReady();

/// Путь в кэше для адреса. Имя файла — хэш адреса, сами адреса длинные.
std::string cachePath(const std::string& url, const char* suffix = ".img");

/// Сколько всего занято в кэше.
struct CacheStats
{
    int files            = 0;
    long long bytes      = 0;
    long long limitBytes = 0;
};

/// Обходит каталог кэша. Долго при тысячах файлов — вызывать из фонового
/// потока, не из отрисовки.
CacheStats cacheStats();

/// Удаляет кэш целиком. Возвращает число удалённых файлов.
int clearCache();

/// Синхронно: сначала кэш, потом сеть. Вызывать только из фонового потока.
std::vector<unsigned char> fetch(const std::string& url);

}  // namespace net
