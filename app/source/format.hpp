#pragma once

#include <string>

/// Чистые преобразования данных каталога в то, что видит пользователь.
///
/// Вынесены в отдельный файл без зависимостей нарочно: так их можно собрать и
/// проверить обычным g++ на машине разработчика, не поднимая ни borealis, ни
/// SQLite, ни тулчейн Switch. Тесты — в tests/test_format.cpp.
namespace fmtx
{

/// Размер картриджа человеку: «4.7 ГБ», «512 МБ». Пустая строка, если размер
/// неизвестен — в базе это ноль.
/// Подписи единиц передаёт вызывающий: «ГБ» была вписана прямо сюда, и при
/// английском интерфейсе карточка показывала «4.7 ГБ». Сама функция остаётся
/// чистой и проверяемой тестами.
std::string formatSize(long long bytes, const char* gigabytes, const char* megabytes);

/// true, если размер удобнее показать в гигабайтах; value получает число в
/// выбранных единицах.
bool sizeInGigabytes(long long bytes, double& value);

/// Сколько языков в строке вида "ru,en,ja". Ноль, если строка пустая.
int languageCount(const std::string& languages);

/// Фирменный цвет игры приходит из eShop строкой вида "0f336f".
/// Возвращает false, если строка не шестизначное шестнадцатеричное число, —
/// тогда вызывающий берёт цвет темы.
bool parseHexColor(const std::string& hex, unsigned char& r, unsigned char& g,
                   unsigned char& b);

/// Относительная яркость по WCAG 2.1: 0 у чёрного, 1 у белого. Не то же самое,
/// что среднее каналов, — глаз втрое чувствительнее к зелёному, чем к красному,
/// и жёлтый фон светлее синего при одинаковой сумме каналов.
double relativeLuminance(unsigned char r, unsigned char g, unsigned char b);

/// Во сколько раз различаются по яркости два цвета. 1 — неразличимы, 21 —
/// чёрное на белом. WCAG требует 4.5 для обычного текста.
double contrastRatio(double luminanceA, double luminanceB);

/// Минимальный контраст текста шапки с фирменным цветом игры.
///
/// Ровно требование WCAG AA для обычного текста. Ниже него подписи на светлых
/// обложках (у половины каталога фирменный цвет — почти белый) переставали
/// читаться.
constexpr double MIN_CONTRAST = 4.5;

/// Подбирает к фирменному цвету читаемый текст, меняя сам цвет как можно
/// меньше.
///
/// Сначала пробуем оставить цвет нетронутым и просто взять тот текст, светлый
/// или тёмный, что различим на нём лучше, — так фон остаётся ровно тем, что
/// прислал eShop. Средние по яркости цвета (насыщенный красный, синий) плохи
/// для обоих, и только тогда фон осветляется или затемняется — по шагу, пока
/// контраста не хватит, с сохранением тона.
///
/// r, g, b правятся на месте. Возвращает true, если текст должен быть тёмным.
bool readableOn(unsigned char& r, unsigned char& g, unsigned char& b);

}  // namespace fmtx
